import json
import uuid
from typing import Any, Dict, List, Optional
from app.core.logging import logger
from app.models.models import TestCase
from app.schemas.schemas import QuestionType
from app.services.providers import get_llm_provider

TESTGEN_SYSTEM_PROMPT = """You are an automated RAG Test Dataset Generator for the AI Truth Inspector platform.
Given an excerpt from a document, generate realistic evaluation test cases covering distinct question types:
- direct_factual: direct retrieval of an explicit fact.
- paraphrased: asking for a fact using synonyms or different phrasing.
- multi_passage: requiring synthesis of multiple sentences or sections.
- numerical: targeting precise numbers, percentages, thresholds, or dates.
- unanswerable: plausible questions related to the topic whose answers are NOT in the text.

You MUST respond strictly with a valid JSON array of objects with the following schema:
[
  {
    "question": "string",
    "question_type": "direct_factual" | "paraphrased" | "multi_passage" | "numerical" | "unanswerable",
    "reference_answer": "string (or 'INSUFFICIENT_EVIDENCE' for unanswerable)",
    "expected_evidence": [
      {
        "page": 1,
        "text_span": "exact quote from the context that provides evidence"
      }
    ],
    "should_abstain": boolean (true for unanswerable, false otherwise),
    "notes": "string"
  }
]"""

def generate_test_cases_from_chunks(
    document_id: str,
    chunks: List[Dict[str, Any]],
    num_cases: int = 5,
    provider_name: str = "anthropic",
    model_name: Optional[str] = None
) -> List[TestCase]:
    """
    Generates test cases from document passages using the configured LLM provider.
    CRITICAL: Generated cases are ALWAYS initialized with status='unverified'.
    """
    context_snippets = []
    for c in chunks[:8]:  # Sample up to 8 chunks
        context_snippets.append(f"[Page {c.get('page', 1)}]: {c.get('text', '')}")

    context_str = "\n\n".join(context_snippets)
    prompt = (
        f"DOCUMENT EXCERPTS:\n{context_str}\n\n"
        f"Generate {num_cases} diverse evaluation test cases covering direct_factual, numerical, paraphrased, "
        "multi_passage, and at least one unanswerable question. Output strictly valid JSON."
    )

    provider = get_llm_provider(model=model_name)
    response = provider.generate(prompt=prompt, system_prompt=TESTGEN_SYSTEM_PROMPT, temperature=0.2)

    raw = response.text.strip()
    if "```json" in raw:
        raw = raw.split("```json")[1].split("```")[0].strip()
    elif "```" in raw:
        raw = raw.split("```")[1].split("```")[0].strip()

    parsed = json.loads(raw)
    created_cases: List[TestCase] = []

    for item in parsed:
        tc_id = f"tc-gen-{uuid.uuid4().hex[:8]}"
        q_type = item.get("question_type", "direct_factual")
        should_abstain = bool(item.get("should_abstain", False)) or q_type == "unanswerable"
        
        tc = TestCase(
            id=tc_id,
            document_id=document_id,
            question=item.get("question", ""),
            question_type=q_type,
            reference_answer=item.get("reference_answer", "INSUFFICIENT_EVIDENCE" if should_abstain else ""),
            expected_evidence_json=json.dumps(item.get("expected_evidence", [])),
            should_abstain=should_abstain,
            status="unverified",  # ALWAYS unverified until human review
            source="generated",
            notes=item.get("notes", "Auto-generated by LLM; pending human verification.")
        )
        created_cases.append(tc)

    logger.info(f"Generated {len(created_cases)} unverified test cases for doc {document_id}")
    return created_cases
